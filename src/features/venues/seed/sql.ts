import type { PreparedSeed } from "./prepare.ts";

type SqlValue = string | number | boolean | null;

export function sqlLiteral(value: SqlValue): string {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot encode non-finite number: ${value}`);
    return String(value);
  }
  return `'${value.replace(/'/g, "''")}'`;
}

export type VenueSqlOptions = {
  /** Visibility of imported venues. They are always `unverified` regardless. */
  status: "draft" | "published";
  sourceFile: string;
};

/**
 * Idempotent SQL for importing venues. Re-running it inserts new venues and refreshes
 * provenance on venues that are still unverified; it never overwrites slugs, operator-verified
 * records, or anything an admin has curated (descriptions, contacts, courts, images).
 */
export function buildVenueSeedSql(seed: PreparedSeed, options: VenueSqlOptions): string {
  const city = seed.city;
  const rows = seed.venues.map((venue) =>
    [
      sqlLiteral(venue.name),
      sqlLiteral(venue.slug),
      sqlLiteral(venue.address),
      sqlLiteral(venue.barangay),
      sqlLiteral(venue.latitude),
      sqlLiteral(venue.longitude),
      sqlLiteral(venue.sourceKey),
      `${sqlLiteral(JSON.stringify(venue.sources))}::jsonb`,
      sqlLiteral(venue.notes),
    ].join(", "),
  );

  return `-- =============================================================================
-- GENERATED by \`pnpm seed:venues\` from ${options.sourceFile}. Do not edit by hand.
-- Dataset: ${seed.dataset}. Venues: ${seed.venues.length}.
--
-- Imported venues are UNVERIFIED. Only names, addresses, barangays, coordinates present in the
-- source, and source references are imported. No prices, facilities, court counts, photos or
-- third-party descriptions. Safe to run repeatedly.
-- =============================================================================

begin;

insert into public.cities (name, slug, province, region, status)
values (${sqlLiteral(city.name)}, ${sqlLiteral(city.slug)}, ${sqlLiteral(city.province)}, ${sqlLiteral(city.region ?? city.province)}, 'published')
on conflict (slug) do nothing;

insert into public.venues (
  city_id, name, slug, address, barangay, latitude, longitude, source_key, source_references,
  data_notes, source_dataset, verification_status, is_test_data, status
)
select
  c.id, v.name::text, v.slug::text, v.address::text, v.barangay::text,
  v.latitude::double precision, v.longitude::double precision, v.source_key::text,
  v.source_references::jsonb, v.data_notes::text, ${sqlLiteral(seed.dataset)}, 'unverified', false, ${sqlLiteral(options.status)}::public.content_status
from (values
  ${rows.map((row) => `(${row})`).join(",\n  ")}
) as v(name, slug, address, barangay, latitude, longitude, source_key, source_references, data_notes)
cross join (select id from public.cities where slug = ${sqlLiteral(city.slug)}) as c
on conflict (source_key) do update set
  name = excluded.name,
  address = excluded.address,
  barangay = excluded.barangay,
  latitude = excluded.latitude,
  longitude = excluded.longitude,
  source_references = excluded.source_references,
  data_notes = excluded.data_notes,
  source_dataset = excluded.source_dataset
where public.venues.verification_status = 'unverified';

commit;
`;
}
